SELECT
    S.GRADE_LEVEL,
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(A.ATTENDANCE_STATUS = 'PRESENT') AS PRESENT_COUNT,
    COUNT_IF(A.ATTENDANCE_STATUS = 'ABSENT') AS ABSENT_COUNT,
    COUNT_IF(A.ATTENDANCE_STATUS = 'TARDY') AS TARDY_COUNT,

    ROUND(
        COUNT_IF(A.ATTENDANCE_STATUS = 'PRESENT')
        / COUNT(*) * 100,
        2
    ) AS ATTENDANCE_RATE,

    ROUND(
        COUNT_IF(A.ATTENDANCE_STATUS = 'ABSENT')
        / COUNT(*) * 100,
        2
    ) AS ABSENCE_RATE,

    CURRENT_TIMESTAMP() AS CREATED_AT

FROM {{ ref('silver_attendance') }} A

INNER JOIN {{ ref('silver_students') }} S
    ON A.STUDENT_ID = S.STUDENT_ID

GROUP BY S.GRADE_LEVEL