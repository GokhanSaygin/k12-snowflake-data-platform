SELECT
    CAMPUS_ID,
    CAMPUS_NAME,
    COUNT(*) AS TOTAL_STUDENTS,

    COUNT_IF(
        CHRONIC_ABSENCE_STATUS = 'CHRONICALLY_ABSENT'
    ) AS CHRONICALLY_ABSENT_STUDENTS,

    ROUND(
        COUNT_IF(CHRONIC_ABSENCE_STATUS = 'CHRONICALLY_ABSENT')
        / COUNT(*) * 100,
        2
    ) AS CHRONIC_ABSENCE_RATE,

    CURRENT_TIMESTAMP() AS CREATED_AT

FROM {{ ref('student_attendance_risk') }}

GROUP BY
    CAMPUS_ID,
    CAMPUS_NAME