SELECT
    TRIM(STUDENT_ID) AS STUDENT_ID,
    TRIM(CAMPUS_ID) AS CAMPUS_ID,
    GRADE_LEVEL,
    ENROLLMENT_DATE,
    UPPER(TRIM(STUDENT_STATUS)) AS STUDENT_STATUS,
    SOURCE_FILE,
    LOADED_AT,
    CURRENT_TIMESTAMP() AS TRANSFORMED_AT
FROM {{ source('bronze', 'students') }}
WHERE STUDENT_ID IS NOT NULL
  AND CAMPUS_ID IS NOT NULL
  AND GRADE_LEVEL BETWEEN 0 AND 12
  AND UPPER(TRIM(STUDENT_STATUS)) IN ('ACTIVE', 'WITHDRAWN')