SELECT
    TRIM(STUDENT_ID) AS STUDENT_ID,
    ATTENDANCE_DATE,
    UPPER(TRIM(ATTENDANCE_STATUS)) AS ATTENDANCE_STATUS,
    SOURCE_FILE,
    LOADED_AT,
    CURRENT_TIMESTAMP() AS TRANSFORMED_AT
FROM {{ source('bronze', 'attendance') }}
WHERE STUDENT_ID IS NOT NULL
  AND ATTENDANCE_DATE IS NOT NULL
  AND UPPER(TRIM(ATTENDANCE_STATUS))
      IN ('PRESENT', 'ABSENT', 'TARDY')

QUALIFY ROW_NUMBER() OVER (
    PARTITION BY STUDENT_ID, ATTENDANCE_DATE
    ORDER BY LOADED_AT DESC
) = 1